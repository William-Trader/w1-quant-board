const DAY_MS = 86400000;

// 北京时间 YYYY-MM-DD
function beijingDate(ts) {
  const d = new Date((ts || Date.now()) + 8 * 3600000);
  return d.toISOString().slice(0, 10);
}

// 偏移 N 天的北京时间日期
function beijingDateOffset(ts, days) {
  return beijingDate((ts || Date.now()) - days * DAY_MS);
}

// 按日期稳定选题：每天同一题，跨天换题
function todayQuestion(ts) {
  const date = beijingDate(ts);
  let h = 0;
  for (let i = 0; i < date.length; i++) h = (h * 31 + date.charCodeAt(i)) >>> 0;
  const q = QUESTIONS[h % QUESTIONS.length];
  return { date, qid: h % QUESTIONS.length, question: q.q, options: q.options, answer: q.answer, explain: q.explain };
}

module.exports = { QUESTIONS, beijingDate, beijingDateOffset, todayQuestion, DAY_MS };
